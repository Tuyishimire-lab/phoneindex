def resolve_soc_telemetry(soc_name: str, is_gaming_fan: bool = False, is_foldable: bool = False) -> Dict[str, Any]:
    """Resolves a chipset name to its full hardware telemetry with thermal form-factor adjustments."""
    for key, val in SOC_TELEMETRY_DB.items():
        if key.lower() in soc_name.lower() or soc_name.lower() in key.lower():
            stab = val["stab"]
            if is_gaming_fan:
                stab = min(96.5, round(stab + 12.0, 1))
            elif is_foldable:
                stab = max(58.0, round(stab - 7.5, 1))
            return {**val, "stab": stab}

    # Default mid-range fallback if unlisted
    return {
        "nm": 6,
        "cpu": "2x 2.4GHz Performance + 6x 2.0GHz Efficiency",
        "gpu": "Integrated Mobile GPU",
        "gbS": 960,
        "gbM": 2650,
        "stab": 91.0,
        "storage": "UFS 3.1",
    }

